#!/usr/bin/env python3

age = int(input("Please tell me your age: "))
print("You are currently " + str(age) + " years old.")

ten_year = age + 10
twenty_year = age + 20
thirty_year = age + 30
print("In 10 years, you'll be " + str(ten_year) + " years old" + ".")
print("In 20 years, you'll be " + str(twenty_year) + " years old" + ".")
print("In 30 years, you'll be " + str(thirty_year) + " years old" + ".")
